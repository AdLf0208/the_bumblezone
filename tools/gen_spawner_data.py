#!/usr/bin/env python3
"""Emit the typed spawner constants the compiled package carries.

The snapshot (`tools/spawner_contract.json`) holds VALUES read from the jar's
nine `worldgen/biome/*.json` spawners objects. This tool renders them as a Rust
static of `SpawnEntry` values — no JSON parser or serde dependency in the
package (registry rule R9 allows only the SDK path dependency), and no jar byte.
The output is rustfmt-stable, so `rustfmt --check` stays green on regeneration.

    python3 tools/gen_spawner_data.py           # write src/spawner_data.rs
    python3 tools/gen_spawner_data.py --check   # assert the tree matches
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
CONTRACT = ROOT / "tools/spawner_contract.json"
OUT = ROOT / "src/spawner_data.rs"


def entry_lines(entry: dict, indent: int) -> list[str]:
    pad = " " * indent
    return [
        f"{pad}SpawnEntry {{",
        f'{pad}    entity: "{entry["type"]}",',
        f'{pad}    weight: {entry["weight"]},',
        f'{pad}    min_count: {entry["minCount"]},',
        f'{pad}    max_count: {entry["maxCount"]},',
        f"{pad}}},",
    ]


def render(snapshot: dict) -> bytes:
    lines = [
        "//! Generated by `tools/gen_spawner_data.py` from `tools/spawner_contract.json`.",
        "//! Values from the jar's nine `worldgen/biome/*.json` `spawners` objects; no jar byte.",
        "//! Do not edit by hand: `python3 tools/gen_spawner_data.py --check` is the gate.",
        "",
        "use super::{SpawnEntry, SpawnTable};",
        "",
        "/// Each biome's non-empty spawn categories, in the artefact's category order.",
        "/// Weights and counts are the jar's values; the 26.3 JSON uses the range shape.",
        "pub static SPAWNERS: &SpawnTable = &[",
    ]
    for biome, categories in sorted(snapshot["biomes"].items()):
        nonempty = [(c, entries) for c, entries in categories.items() if entries]
        if not nonempty:
            continue
        lines.append("    (")
        lines.append(f'        "the_bumblezone:{biome}",')
        if len(nonempty) == 1:
            category, entries = nonempty[0]
            lines.append("        &[(")
            lines.append(f'            "{category}",')
            lines.append("            &[")
            for entry in entries:
                lines.extend(entry_lines(entry, 16))
            lines.append("            ],")
            lines.append("        )],")
        else:
            lines.append("        &[")
            for category, entries in nonempty:
                lines.append("            (")
                lines.append(f'                "{category}",')
                lines.append("                &[")
                for entry in entries:
                    lines.extend(entry_lines(entry, 20))
                lines.append("                ],")
                lines.append("            ),")
            lines.append("        ],")
        lines.append("    ),")
    lines += ["];", ""]
    return "\n".join(lines).encode("utf-8")


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    snapshot = json.loads(CONTRACT.read_text())
    want = render(snapshot)
    if args.check:
        actual = OUT.read_bytes() if OUT.is_file() else b""
        if actual != want:
            print("FAIL src/spawner_data.rs differs from the contract generator", file=sys.stderr)
            return 1
        print(f"OK    src/spawner_data.rs matches the contract ({len(want)} bytes)")
        return 0
    OUT.write_bytes(want)
    print(f"wrote {OUT.relative_to(ROOT)} ({len(want)} bytes)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
